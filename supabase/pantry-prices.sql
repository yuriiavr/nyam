-- Ціна продукту в коморі: скільки коштував грам в останній покупці.
--
-- Навіщо: рівень вартості страви («дешево / дорого») автор рецепта ставить
-- на око, і для чужої кухні він майже нічого не означає. Сканер чека знає
-- точну ціну — і тоді вартість страви рахується тією ж арифметикою, що й
-- калорії: звести все до грамів і помножити.
--
-- Через грам, а не за кілограм чи за штуку, бо це спільний знаменник:
-- рецепт просить склянку, чек рахував кілограми, на упаковці мілілітри.
--
-- Виконувати лише тим, у кого база вже створена за старою schema.sql:
-- у новій ця колонка вже є. Скрипт безпечно запускати повторно.

alter table public.pantry_items
  add column if not exists price_per_gram numeric(10, 6);

comment on column public.pantry_items.price_per_gram is
  'Ціна грама продукту в гривнях з останньої покупки; null — ціна невідома.';

-- PostgREST тримає схему в кеші й про нову колонку сам може не дізнатись.
-- Без цього рядка читання комори падатиме з «column does not exist» навіть
-- після успішної міграції.
notify pgrst, 'reload schema';
