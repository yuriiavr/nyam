/**
 * Будильник готування з сервера: чиста частина.
 *
 * Окремо від push-server.ts навмисно. Той імпортує "server-only", який поза
 * серверною збіркою Next кидає помилку, — і скрипти перевірок (npm run
 * check:push) не могли б його завантажити. А саме тут живуть числа, що мусять
 * збігатися з supabase/timer-push.sql, і вибір, кому дзвонити, — тобто те, що
 * найлегше тихо зламати. Тож жодних залежностей: ні бази, ні мережі.
 *
 * Імпортувати лише звідси, і push-server.ts цього далі не передає: сторінка
 * готування теж бере тут TIMER_STALE_MS, а той самий імпорт через push-server
 * затягнув би в клієнтську збірку "server-only" і web-push — і збірка впала б.
 */

/**
 * Будильник, який чекає свого часу в таблиці timer_pushes.
 *
 * Потрібен через iPhone: застосунок на екрані «Домів», щойно його згорнули,
 * заморожується цілком, і місцевий таймер не доживає до нуля — дзвонить лише
 * тоді, коли застосунок відкрили знову. Пуш із сервера приходить і в
 * закритий, тож момент дзвінка тримає база, а не телефон.
 */
export interface TimerPushRow {
  id: string;
  user_id: string;
  fire_at: string;
  title: string;
  body: string;
  url: string | null;
  /**
   * Підписка пристрою, на якому запустили таймер. Дзвонимо лише туди: макарони
   * вариш із телефоном у руці, і «час вийшов» на ноутбуці в іншій кімнаті —
   * шум, а не будильник. null буває лише в рядків, записаних до появи колонки.
   */
  endpoint: string | null;
}

/**
 * Колонки, які забирає маршрут розсилки. Одним рядком тут, а не в маршруті, —
 * щоб перевірка могла звірити їх зі схемою в supabase/timer-push.sql.
 */
export const TIMER_PUSH_COLUMNS = "id,user_id,fire_at,title,body,url,endpoint";

/**
 * На скільки раніше строку забираємо будильник.
 *
 * Між «час настав» і дзвінком у кишені — крок розкладу бази (до 5 с), виклик
 * маршруту й доставка службою Apple чи Google (секунда-дві). Без запасу
 * будильник запізнювався б у середньому секунд на пʼять; із ним приходить
 * приблизно вчасно. Більше не беремо: пауза за мить до кінця інакше вже не
 * встигала б його скасувати.
 *
 * Те саме число стоїть у dispatch_timer_pushes (supabase/timer-push.sql) —
 * інакше база кликатиме маршрут не тоді, коли він готовий щось забрати.
 * Розбіжність ловить npm run check:push.
 */
export const TIMER_LEAD_MS = 2_000;

/**
 * Скільки може прожити будильник у дорозі до пристрою.
 *
 * Дві хвилини: «час вийшов», що доїхав через годину, коли телефон нарешті
 * зловив мережу, — вже не будильник, а плутанина.
 */
export const TIMER_TTL_SEC = 120;

/**
 * Будильник, що прострочився більше ніж на стільки, не надсилаємо.
 *
 * Так буває лише після збою самої розсилки — розклад зупинявся, секрет не
 * зійшовся, — і коли її полагодять, людині не мають посипатись усі вчорашні
 * «час вийшов» разом.
 *
 * Та сама межа стоїть у dispatch_timer_pushes: заради такого рядка база
 * маршрут уже не кличе, тож зламана розсилка не смикається без кінця. Її теж
 * звіряє npm run check:push.
 */
export const TIMER_STALE_MS = 10 * 60_000;

/**
 * Скільки будильників одного пристрою надсилати за один виклик розсилки.
 *
 * Таймерів тепер кілька — по кроку, і в двох рецептах разом, — і в кожного
 * свій тег, тож два «час вийшов», що зійшлися в одну секунду, мають прийти
 * обидва. Але рядки пише сам користувач, і сотня його будильників на ту саму
 * секунду не має стати сотнею запитів до служби пуша: беремо кілька
 * найпізніших, а решта — однаково шум. Із запасом на реальну кухню: чотири
 * таймери, що скінчились у ті самі пʼять секунд, — це вже рідкість.
 */
export const TIMER_BURST_PER_DEVICE = 4;

/**
 * Що з забраних будильників справді надіслати.
 *
 * На пристрій — не більше TIMER_BURST_PER_DEVICE, найпізніші. Саме на
 * пристрій, а не на людину: будильник дзвонить лише там, де його запустили,
 * і таймери на ноутбуці не мають зʼїсти таймер на телефоні, що закінчився в
 * ту саму секунду.
 *
 * Чиста функція — щоб перевірити без бази й без мережі.
 */
export function pickDueTimers(
  rows: TimerPushRow[],
  now: number,
): { due: TimerPushRow[]; stale: number } {
  const byDevice = new Map<string, TimerPushRow[]>();
  let stale = 0;

  for (const row of rows) {
    const at = Date.parse(row.fire_at);
    // Зіпсована дата — теж прострочене: невідомо, коли він мав дзвонити.
    if (!(at >= now - TIMER_STALE_MS)) {
      stale += 1;
      continue;
    }
    // Пробіл не трапляється ні в uuid, ні в адресі підписки — ключі не зіллються.
    const device = `${row.user_id} ${row.endpoint ?? ""}`;
    const list = byDevice.get(device);
    if (list) list.push(row);
    else byDevice.set(device, [row]);
  }

  const due: TimerPushRow[] = [];
  for (const list of byDevice.values()) {
    list.sort((a, b) => Date.parse(b.fire_at) - Date.parse(a.fire_at));
    due.push(...list.slice(0, TIMER_BURST_PER_DEVICE));
  }
  return { due, stale };
}

/**
 * Тег сповіщення будильника: свій у кожного таймера, спільний для серверного
 * й місцевого дзвінка того самого відліку — встигли обидва, на екрані одне.
 * Ним же позначає сповіщення місцевий будильник (showLocalAlarm у src/lib/cook-alarms.ts).
 */
export function timerTag(id: string): string {
  return `nyam-timer:${id}`;
}

/**
 * Адреса будильника: куди веде натиск на сповіщення — і з чого загублений
 * будильник повертають на екран (CookingHost): рецепт і крок записані в самій
 * адресі. Тут, а не в cook-alarms.ts, — щоб npm run check:push звірив, що
 * адреса читається назад.
 */
export function alarmUrl(recipeId: string, step: number): string {
  return `/recipe/${recipeId}/cook?step=${step}`;
}

export function parseAlarmUrl(url: string | null | undefined): { recipeId: string; step: number } | null {
  const match = url?.match(/^\/recipe\/([^/?#]+)\/cook\?step=(\d+)$/);
  if (!match) return null;
  try {
    return { recipeId: decodeURIComponent(match[1]), step: Number(match[2]) };
  } catch {
    return null;
  }
}
