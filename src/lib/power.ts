import type { Recipe } from "./types";

/**
 * Що страва вимагає від кухні: духовку, плиту, розетку.
 *
 * Потрібно через відключення світла. «Скільки готувати» тут недостатньо:
 * тридцятихвилинна страва в духовці неможлива, коли світла немає взагалі, а
 * така сама тридцятихвилинна на газовій плиті — цілком.
 *
 * Визначаємо по тексту кроків, бо в рецептах немає поля «чим готувати» і
 * додавати його заднім числом до всіх наявних рецептів нема кому. Це
 * здогадка, і вона свідомо перестраховується: краще показати страву як
 * таку, що потребує плити, ніж пообіцяти вечерю без вогню й помилитись.
 */

export interface CookingNeeds {
  /** Духовка: довгий розігрів і майже завжди електрика. */
  oven: boolean;
  /** Плита: сковорідка, каструля, вок. На газі працює й без світла. */
  stove: boolean;
  /** Прилад у розетку: блендер, мікрохвильовка, мультиварка. */
  appliance: boolean;
}

const OVEN = ["духовк", "запік", "запеч", "випік", "пропеч", "деко", "аерогриль"];

const STOVE = [
  "сковор", "пательн", "каструл", "сотейник", "казан", "вок",
  "обсмаж", "підсмаж", "смаж", "пасеру", "фритюр",
  "вари", "відвар", "прокип", "кипят", "тушк", "припуст", "бланшу", "на вогні",
];

const APPLIANCE = [
  "блендер", "міксер", "мікрохвил", "мультивар", "тостер", "комбайн",
  "соковижим", "кавовар", "фритюрниц", "електрочайник", "вафельниц", "млинцевиц",
  /*
   * «Пробий нут з тахіні», «пробий ягоди з бананом» — прилад у цих кроках
   * не названий, але іншого способу немає. Саме так написані хумус і смузі
   * у наших рецептах, і без цих двох слів вони потрапляли в добірку
   * «без вогню», де на них не вистачило б розетки.
   */
  "проби", "переби",
];

const hit = (text: string, words: string[]) => words.some((w) => text.includes(w));

/** Читає з кроків рецепта, чим саме його готують. */
export function cookingNeeds(recipe: Recipe): CookingNeeds {
  const text = recipe.steps
    .map((s) => `${s.text} ${s.tip ?? ""}`)
    .join(" ")
    .toLowerCase()
    .replace(/[ʼ’`´]/g, "'");

  return {
    oven: hit(text, OVEN),
    stove: hit(text, STOVE),
    appliance: hit(text, APPLIANCE),
  };
}

/** Чи потрібне цій страві тепло взагалі. */
export const needsHeat = (needs: CookingNeeds) => needs.oven || needs.stove;

/**
 * Чи потрібна розетка.
 *
 * Газову плиту сюди не рахуємо — вона працює й у темряві. Духовку рахуємо:
 * газові духовки є, але електричних більше, і помилитись у цей бік
 * безпечніше, ніж пообіцяти запіканку під час відключення.
 */
export const needsSocket = (needs: CookingNeeds) => needs.oven || needs.appliance;

export type PowerMode =
  /** Світло є, але ненадовго: вкластися у вікно. */
  | "window"
  /** Світла немає, газ є: плита працює, розетки ні. */
  | "socket"
  /** Ані світла, ані вогню: тільки те, що не готують. */
  | "cold";

export interface PowerMatch {
  recipe: Recipe;
  needs: CookingNeeds;
}

/**
 * Страви, які реально приготувати за поточних умов.
 *
 * `minutes` обмежує час — вікно між відключеннями зазвичай відоме наперед.
 * Порядок — від найшвидшого: коли світло дають на дві години, найдовша
 * страва в списку найменш корисна.
 */
export function powerMatches(
  recipes: Recipe[],
  { mode, minutes }: { mode: PowerMode; minutes?: number | null },
): PowerMatch[] {
  return recipes
    .map((recipe) => ({ recipe, needs: cookingNeeds(recipe) }))
    .filter(({ recipe, needs }) => {
      if (minutes != null && recipe.timeMin > minutes) return false;
      if (mode === "socket") return !needsSocket(needs);
      if (mode === "cold") return !needsHeat(needs) && !needs.appliance;
      return true;
    })
    .sort((a, b) => a.recipe.timeMin - b.recipe.timeMin);
}
