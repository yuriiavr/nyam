/**
 * Штрихкод EAN у тій формі, в якій його знає спільна база.
 *
 * Дзеркало SQL-функції public.normalize_ean (supabase/products.sql) — рядок у
 * рядок, з тими самими векторами в scripts/check-products.mjs. Навіщо дзеркало,
 * якщо нормалізацію рахує лише база: клієнт мусить знати ЗАЗДАЛЕГІДЬ, чи йти з
 * кодом у resolve_identifiers і в Open Food Facts, і чи впізнати його в
 * офлайн-кеші (eanIndex). Розійдуться правила — код, який база відкине, клієнт
 * шукатиме вічно, або навпаки: знайомий товар в офлайні не впізнається.
 *
 * Тому тут ніякої «розумності» понад SQL. Змінюєш одне — міняй обидва й вектори.
 */

/**
 * Код → 8 чи 13 цифр або null.
 *
 * - лишає самі цифри (пробіли й дефіси з етикетки не заважають);
 * - UPC-A (12 цифр) доповнює нулем до EAN-13;
 * - внутрішні коди магазину (EAN-13 з 2…, 02…, 04…; EAN-8 з 2…) — null: вони
 *   означають різне в кожній мережі, і вчити ними спільну базу не можна;
 * - заглушки кас («4820000000000»: після префікса самі нулі) і коди з однієї
 *   цифри — null: контрольну цифру такі проходять, а товару за ними немає;
 * - неправильна контрольна цифра — null.
 *
 * Увага: як і SQL, цифри витягує з будь-якого рядка, тож «AB-12345670» стане
 * EAN-8. Сканер, який знає формат (Code-128), має відсіяти такі сам.
 */
export function normalizeEan(raw: string | null | undefined): string | null {
  let d = (raw ?? "").replace(/\D/g, "");
  if (d.length === 12) d = `0${d}`;
  const n = d.length;
  if (n !== 8 && n !== 13) return null;

  if ((n === 13 && (d.startsWith("2") || d.startsWith("02") || d.startsWith("04"))) || (n === 8 && d.startsWith("2"))) {
    return null;
  }

  // substr(d, 4, n - 4) у SQL: з четвертої позиції, без контрольної цифри.
  if (/^0+$/.test(d.slice(3, n - 1)) || /^(\d)\1+$/.test(d)) return null;

  // Ваги 3 і 1 чергуються від цифри перед контрольною — однаково для EAN-8 і EAN-13.
  let sum = 0;
  for (let i = 1; i <= n - 1; i++) sum += Number(d[n - 1 - i]) * (i % 2 === 1 ? 3 : 1);
  return (10 - (sum % 10)) % 10 === Number(d[n - 1]) ? d : null;
}
