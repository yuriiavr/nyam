/**
 * Публічний ключ для підписки на сповіщення.
 *
 * Чому окремий маршрут, а не змінна з префіксом NEXT_PUBLIC_: такою змінною
 * не можна зробити sensitive-значення у Vercel, а всі ключі проєкту додані
 * саме так. Ключ від цього нічого не втрачає — він публічний за призначенням
 * і однаково опиняється в кожному браузері, що підписався.
 *
 * Порожня відповідь означає «пуш не налаштовано». Це не помилка: без ключів
 * застосунок просто не показує перемикач.
 */

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export function GET(): Response {
  const key = process.env.NEXT_PUBLIC_VAPID_PUBLIC_KEY ?? process.env.VAPID_PUBLIC_KEY ?? "";

  return Response.json(
    { key },
    {
      headers: {
        // Ключ міняється раз на ніколи, але й кешувати його назавжди не варто:
        // після заміни пари підписки треба перевипускати.
        "Cache-Control": "public, max-age=300",
      },
    },
  );
}
